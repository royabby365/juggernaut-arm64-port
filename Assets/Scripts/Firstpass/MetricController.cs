	public void OnActivityStart(string param)
	{
		SessionTicks = DateTime.Now.Ticks;
		AddMetric(LoginMetricId, 1);
		if (!RegisterSended)
		{
			AddMetric(RegisterMetricId, 1);
			AddStat(11);
			RegisterSended = true;
		}
		AddStat(1);
	}

