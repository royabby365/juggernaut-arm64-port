	{
		GetDataAboutMoney();
	}

	public void OnActivityStop(string param)
	{
		TimeSpan timeSpan = new TimeSpan(DateTime.Now.Ticks - SessionTicks);
		int value = (int)timeSpan.TotalSeconds;
		AddMetric(SessionMetricId, value);
		AddStat(2);
	}

	public void OnLowMemory(string available)
	{
		long num = long.Parse(available) / 1024 / 1024;
		AddMetric(MemotyWarningMetricId, (int)num);
	}

	public void OnRegisteredForRemoteNotifications(string registrationId)
	{
		Debug.Log("MetricContoller.OnRegisteredForRemoteNotifications(" + registrationId + ")");
		UniqueData.DeviceToken = registrationId;
		AddStat(10);
	}

	public void AddGameState(int level, int gold, int diamonds, int areaId, int mobIndex, int raceId, int exp)
	{
		GameState = NetworkSender.GetStatRequestDict();
		GameState["l"] = level.ToString();
		GameState["m[1]"] = gold.ToString();
		GameState["m[2]"] = diamonds.ToString();
		GameState["loc"] = areaId.ToString();
		GameState["bot"] = mobIndex.ToString();
		GameState["r"] = raceId.ToString();
		GameState["exp"] = exp.ToString();
	}

	public void AddAchivStateAndSend(List<GameEvents.Event> events)
	{
		if (GameState == null)
		{
			GameState = NetworkSender.GetStatRequestDict();
		}
		List<GameEvents.Event> list = new List<GameEvents.Event>(events);
		list.Sort(new AchievementComparer());
		foreach (GameEvents.Event item in list)
		{
			int num = (int)(100f * (float)item.Progress / (float)item.MaxProgress);
			string key = $"a[{item.Achievement.Id}]";
			GameState[key] = num.ToString();
		}
		if (GameState.Count > 0)
		{
			string body = GameStateToString(GameState);
			GameState = null;
			StartCoroutine(NetworkSender.SendStatRequest(body));
		}
	}

	public void GetDataAboutMoney()
	{
		if (UniqueData.InGame)
		{
			StartCoroutine(NetworkSender.SendMoneyRequest(OnMoneyFromServer));
		}
	}

	public void RateApp()
	{
		MetricProxy.Call("RateApp");
	}

	private string GameStateToString(Dictionary<string, string> state)
	{
		string text = string.Empty;
		foreach (KeyValuePair<string, string> item in GameState)
		{
			if (text.Length > 0)
			{
				text += "&";
			}
			text = text + item.Key + "=" + item.Value;
		}
		return text + "&sig=1";
	}

	private string GetMoneySignature(string moneyStr)
	{
		string serverSignatureSalt = UnityApi.GetServerSignatureSalt();
		return (moneyStr.MD5() + serverSignatureSalt).MD5();
	}

	private void OnMoneyFromServer(string json)
	{
		Utils.LogForce("OnMoneyFromServer, json: " + json);
		Dictionary<string, object> dictionary = Json.Deserialize(json) as Dictionary<string, object>;
		try
		{
			string text = dictionary["data"] as string;
			string text2 = dictionary["signature"] as string;
			Dictionary<string, object> dictionary2 = Json.Deserialize(text) as Dictionary<string, object>;
			string moneySignature = GetMoneySignature(text);
			Utils.LogForce("OnMoneyFromServer, calculated signature: " + moneySignature);
			if (moneySignature == text2)
			{
				Dictionary<string, object> dictionary3 = dictionary2["money"] as Dictionary<string, object>;
				if (dictionary3.ContainsKey("1"))
				{
					SingletonT<ServerData>.I.GiveMoney(ServerData.MoneyType.TypeE.Gold, dictionary3["1"] as string);
				}
				if (dictionary3.ContainsKey("2"))
				{
					SingletonT<ServerData>.I.GiveMoney(ServerData.MoneyType.TypeE.Diamond, dictionary3["2"] as string);
				}
			}
			else
			{
				Utils.LogForce("OnMoneyFromServer, cheat detected!");
			}
		}
		catch (Exception ex)
		{
			Utils.LogForce("OnMoneyFromServer FAILED", ex.Message, ex.StackTrace);
		}
	}
