	public void AddMetric(int type, int value, int level, int objectInt)
	{
		StartCoroutine(NetworkSender.SendMetric(MapMetricType(type), value, level, objectInt));
	}

	public void AddMetric(int type, int value)
	{
		AddMetric(type, value, 0, 0);
	}

	public void AddStat(int eventId, int subEventId)
	{
		SyncOpenUDID();
		StartCoroutine(NetworkSender.SendStat(eventId, subEventId));
	}

	public void AddStat(int eventId)
	{
		AddStat(eventId, 0);
